class Solution {
  public:
    int findCeil(Node* root, int x) {
        // code here
        Node* temp = root;
        int ans = -1;
        
        
        while(temp){
            if(temp->data >= x){
                ans = temp->data;
                temp = temp->left;
            }
            else{
                temp = temp->right;
            }
        }
        
        return ans;
    }
};


