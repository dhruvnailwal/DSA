class Solution {
  public:
    int findMaxFork(Node* root, int k) {
        // code here
        Node *temp = root;
        int ans = -1;
        while(temp){
            if(temp->data <= k){
                ans = temp->data;
                temp = temp->right;
            }
            else{
                temp = temp->left;
            }
        }
        
        return ans;
    }
};

